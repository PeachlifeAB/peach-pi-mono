#!/usr/bin/env node
// Render a package's import graph as a Mermaid diagram (--out <file.md>).
// Consumes `madge --json` (which needs no Graphviz), so the graph regenerates
// anywhere without a system binary. A PNG/SVG via `madge --image` is optional
// and requires Graphviz (brew install graphviz).
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const [outFlag, out, ...roots] = process.argv.slice(2);
if (outFlag !== "--out" || !out || roots.length === 0) {
	process.stderr.write("usage: gen-dependency-graph.mjs --out <file.md> <src-dir> [<src-dir> ...]\n");
	process.exit(2);
}

const raw = execFileSync("npx", ["madge", "--extensions", "ts", "--json", ...roots], {
	encoding: "utf8",
});
const graph = JSON.parse(raw);

const id = (path) => path.replace(/[^a-zA-Z0-9]/g, "_");
const lines = ["```mermaid", "graph LR"];
for (const [from, targets] of Object.entries(graph)) {
	if (targets.length === 0) {
		lines.push(`  ${id(from)}["${from}"]`);
		continue;
	}
	for (const to of targets) lines.push(`  ${id(from)}["${from}"] --> ${id(to)}["${to}"]`);
}
lines.push("```");

const outPath = resolve(out);
writeFileSync(outPath, `# Dependency graph\n\nGenerated by \`npm run docs:graph\`.\n\n${lines.join("\n")}\n`);
process.stdout.write(`wrote ${outPath}\n`);
